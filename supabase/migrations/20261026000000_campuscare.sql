-- CampusCare complaint management schema, authorization, and initial setup.
-- Apply once to a new Supabase project with the SQL Editor or Supabase CLI.

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;
grant usage on schema private to authenticated;

create table if not exists public.profiles (
    id uuid primary key references auth.users (id) on delete cascade,
    full_name text not null check (char_length(full_name) between 1 and 100),
    role text not null default 'student' check (role in ('student', 'admin')),
    created_at timestamptz not null default pg_catalog.now()
);

create table if not exists public.complaints (
    id uuid primary key default gen_random_uuid(),
    ticket_number bigint generated by default as identity (start with 100001) unique,
    user_id uuid not null default auth.uid() references public.profiles (id) on delete restrict,
    category text not null check (category in ('classroom', 'laboratory', 'water', 'electricity', 'cleanliness', 'hostel', 'other')),
    title text not null check (char_length(title) between 1 and 120),
    location text not null check (char_length(location) between 1 and 160),
    description text not null check (char_length(description) between 1 and 3000),
    status text not null default 'submitted' check (status in ('submitted', 'in_progress', 'resolved', 'rejected')),
    admin_note text check (admin_note is null or char_length(admin_note) <= 3000),
    handled_by uuid references public.profiles (id) on delete set null,
    created_at timestamptz not null default pg_catalog.now(),
    updated_at timestamptz not null default pg_catalog.now()
);

create index if not exists complaints_user_created_idx
    on public.complaints (user_id, created_at desc);
create index if not exists complaints_status_created_idx
    on public.complaints (status, created_at desc);
create index if not exists complaints_category_created_idx
    on public.complaints (category, created_at desc);

create or replace function private.is_management()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.profiles as p
        where p.id = (select auth.uid())
          and p.role = 'admin'
    );
$$;

revoke all on function private.is_management() from public, anon;
grant execute on function private.is_management() to authenticated;

create or replace function private.create_profile_for_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    requested_name text;
begin
    requested_name := pg_catalog.btrim(coalesce(new.raw_user_meta_data ->> 'full_name', ''));
    if requested_name = '' then
        requested_name := coalesce(
            nullif(pg_catalog.split_part(coalesce(new.email, ''), '@', 1), ''),
            'Campus user'
        );
    end if;

    insert into public.profiles (id, full_name)
    values (new.id, pg_catalog.left(requested_name, 100))
    on conflict (id) do nothing;

    return new;
end;
$$;

revoke all on function private.create_profile_for_new_auth_user() from public, anon, authenticated;

drop trigger if exists on_auth_user_created_campuscare on auth.users;
create trigger on_auth_user_created_campuscare
    after insert on auth.users
    for each row execute function private.create_profile_for_new_auth_user();

create or replace function private.set_complaint_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at := pg_catalog.now();
    return new;
end;
$$;

revoke all on function private.set_complaint_updated_at() from public, anon, authenticated;

drop trigger if exists set_campuscare_complaint_updated_at on public.complaints;
create trigger set_campuscare_complaint_updated_at
    before update on public.complaints
    for each row execute function private.set_complaint_updated_at();

alter table public.profiles enable row level security;
alter table public.complaints enable row level security;

revoke all on table public.profiles from public, anon, authenticated;
grant select on table public.profiles to authenticated;

revoke all on table public.complaints from public, anon, authenticated;
grant select on table public.complaints to authenticated;
grant insert (category, title, location, description) on table public.complaints to authenticated;
grant update (status, admin_note, handled_by) on table public.complaints to authenticated;

revoke all on sequence public.complaints_ticket_number_seq from public, anon, authenticated;
grant usage, select on sequence public.complaints_ticket_number_seq to authenticated;

drop policy if exists profiles_select_own on public.profiles;
create policy profiles_select_own
    on public.profiles
    for select
    to authenticated
    using (id = (select auth.uid()));

drop policy if exists complaints_select_owner_or_management on public.complaints;
create policy complaints_select_owner_or_management
    on public.complaints
    for select
    to authenticated
    using (
        user_id = (select auth.uid())
        or (select private.is_management())
    );

drop policy if exists complaints_insert_own on public.complaints;
create policy complaints_insert_own
    on public.complaints
    for insert
    to authenticated
    with check (
        user_id = (select auth.uid())
        and status = 'submitted'
        and admin_note is null
        and handled_by is null
    );

drop policy if exists complaints_update_management on public.complaints;
create policy complaints_update_management
    on public.complaints
    for update
    to authenticated
    using ((select private.is_management()))
    with check ((select private.is_management()));

-- There is intentionally no browser DELETE policy or grant: complaint history is retained.